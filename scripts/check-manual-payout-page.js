const fs = require('fs')

const page = fs.readFileSync('src/views/activity/rewardDetail/index.vue', 'utf8')
const permission = fs.readFileSync('src/store/modules/permission.js', 'utf8')

function assertIncludes(source, expected, message) {
  if (!source.includes(expected)) {
    throw new Error(message)
  }
}

assertIncludes(permission, "path: 'manualPayout'", '活动管理缺少手动派彩菜单')
assertIncludes(permission, "title: '手动派彩'", '手动派彩菜单标题不正确')
assertIncludes(permission, "component: 'activity/rewardDetail/index'", '手动派彩未复用奖励明细页面')
assertIncludes(page, "this.$route.path.includes('/activity/manualPayout')", '手动派彩页面缺少路由模式判断')
assertIncludes(page, '手动派彩列表', '手动派彩页面缺少列表标题')
assertIncludes(page, 'Array.from({ length: 200 }', '手动派彩页面未生成200条演示数据')
assertIncludes(page, "{ type: '累充活动', name: '累计充值奖励活动' }", '手动派彩活动类型缺少累充活动')
assertIncludes(page, "{ type: '有效投注额', name: '有效投注额达标奖励' }", '手动派彩活动类型缺少有效投注额')
assertIncludes(page, 'v-if="canManualPayout(row)"', '手动派彩按钮未按领取状态控制')
assertIncludes(page, "Number(row && row.bonusStatus) === 1", '手动派彩按钮未限定已达标状态')
assertIncludes(page, "1: '已达标'", '手动派彩状态缺少已达标')
assertIncludes(page, "2: '已派彩'", '手动派彩状态缺少已派彩')
assertIncludes(page, "3: '已领取'", '手动派彩状态缺少已领取')
assertIncludes(page, "return this.isManualPayout ? '状态' : '领取状态'", '手动派彩筛选未改为状态')
assertIncludes(page, "return this.isManualPayout ? '派彩时间' : '达标时间'", '手动派彩列表未改为派彩时间')
assertIncludes(page, '<el-table-column v-if="!isManualPayout" label="任务名称"', '手动派彩列表仍展示任务名称字段')
assertIncludes(page, "this.$set(row, 'bonusStatusLabel', '已派彩')", '派彩后未更新为已派彩')
assertIncludes(page, "this.$set(row, 'payoutTime', payoutTime)", '派彩后未写入派彩时间')
assertIncludes(page, 'ref="manualPayoutTable"', '手动派彩列表缺少表格引用')
assertIncludes(page, '@selection-change="handleManualPayoutSelectionChange"', '手动派彩列表缺少勾选事件')
assertIncludes(page, ':selectable="isManualPayoutRowSelectable"', '手动派彩列表未限制仅已达标数据可选')
assertIncludes(page, 'selectedManualPayoutRows.length > 0', '选中已达标数据后未展示批量手动派彩按钮')
assertIncludes(page, '批量手动派彩（{{ selectedManualPayoutRows.length }}）', '批量手动派彩按钮未展示选中数量')
assertIncludes(page, 'async handleBatchManualPayout()', '手动派彩页面缺少批量派彩方法')
assertIncludes(page, 'this.applyManualPayout(this.selectedManualPayoutRows, payoutTime)', '批量派彩未复用统一状态更新逻辑')
assertIncludes(page, "this.$modal.msgSuccess(`批量手动派彩成功，共派彩 ${payoutCount} 条数据`)", '批量派彩成功提示不正确')
assertIncludes(page, 'this.clearManualPayoutSelection()', '筛选或翻页后未清空手动派彩勾选状态')
assertIncludes(page, 'v-if="isManualPayout" class="filter-item" prop="payoutDateRange"', '手动派彩页面缺少派彩时间筛选项')
assertIncludes(page, '<span>派彩时间</span>', '派彩时间筛选项标题不正确')
assertIncludes(page, 'v-model="payoutDateRange"', '派彩时间筛选未绑定日期时间范围')
assertIncludes(page, "type=\"datetimerange\"", '派彩时间筛选未支持日期及时分秒')
assertIncludes(page, 'params.payoutStartDate', '派彩时间筛选缺少开始时间参数')
assertIncludes(page, 'params.payoutEndDate', '派彩时间筛选缺少结束时间参数')
assertIncludes(page, 'this.payoutDateRange = []', '重置操作未清空派彩时间筛选')

console.log('manual payout page check passed')
